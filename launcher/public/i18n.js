window.LANG = localStorage.getItem('lc-lang') || 'zh'
window.T = (key, vars) => {
  let s = (window.I18N[window.LANG] ?? window.I18N.zh)[key] ?? window.I18N.zh[key] ?? key
  for (const [k, v] of Object.entries(vars ?? {})) s = s.replace('{' + k + '}', v)
  return s
}
window.applyI18n = () => {
  document.documentElement.lang = window.LANG === 'zh' ? 'zh-CN' : 'en'
  for (const el of document.querySelectorAll('[data-t]')) el.textContent = window.T(el.dataset.t)
  for (const el of document.querySelectorAll('[data-t-ph]')) el.placeholder = window.T(el.dataset.tPh)
}
